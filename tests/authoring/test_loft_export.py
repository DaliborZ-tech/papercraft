@pytest.mark.parametrize("kind", ["svg", "pdf"])
def test_actual_staged_loft_shift_is_rejected_and_all_old_bytes_preserved(
    tmp_path, monkeypatch, kind
):
    p, _, _ = simple_project()
    snapshot = p.snapshot()
    directory = tmp_path / "bundle"
    author_export.export_all(snapshot, directory)
    (directory / "foreign.txt").write_bytes(b"owner's unrelated bytes")
    before = hashes(directory)
    original = getattr(author_export, "_" + kind)

    def corrupt(*args, **kwargs):
        result = original(*args, **kwargs)
        path = args[4] if kind == "svg" else args[3]
        if kind == "svg":
            tree = ET.parse(path)
            group = tree.getroot().find(NS + "g")
            group.set("transform", "translate(26 25) rotate(0)")
            tree.write(path, encoding="utf-8", xml_declaration=True)
        else:
            reader = PdfReader(path)
            writer = PdfWriter()
            for page in reader.pages:
                content, count = re.subn(
                    rb"1 0 -?0 1 25 25 cm",
                    b"1 0 0 1 26 25 cm",
                    page.get_contents().get_data(),
                )
                assert count == 1  # A mutation harness must actually corrupt it.
                stream = DecodedStreamObject()
                stream.set_data(content)
                page[NameObject("/Contents")] = stream
                writer.add_page(page)
            with open(path, "wb") as output:
                writer.write(output)
        return result

    monkeypatch.setattr(author_export, "_" + kind, corrupt)
    with pytest.raises(CurveOutputError):
        author_export.export_all(snapshot, directory)
    assert hashes(directory) == before


