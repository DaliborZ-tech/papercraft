@pytest.mark.parametrize(
    "mutation", ["profile_uuid", "profile_revision", "source_geometry", "patch"]
)
def test_actual_source_binding_rejects_swapped_uuid_revision_geometry_or_patch(mutation):
    p, sid, _ = simple_project()
    snapshot = p.snapshot()
    report = snapshot["construction_checks"]["lofts"][sid]
    if mutation == "profile_uuid":
        report["source_binding"]["profiles"][0]["id"] = p.project_id
    elif mutation == "profile_revision":
        report["source_binding"]["profiles"][0]["revision"] += 1
    elif mutation == "source_geometry":
        report["source_binding"]["profiles"][0]["vertices"][1]["point"][0] += 1
    else:
        report["patches"][0]["first_segment_id"] = p.project_id
    with pytest.raises(CurveOutputError):
        validate_loft_snapshot(snapshot)


def test_direct_source_area_rejects_two_individually_small_stage_drifts(tmp_path, monkeypatch):
    """SK011/V02: 300→300.009→300.018 may not get two fresh .01 budgets."""
    p, sid, _ = simple_project()
    snapshot = p.snapshot()
    directory = tmp_path / "bundle"
    author_export.export_all(snapshot, directory)
    (directory / "foreign.txt").write_bytes(b"preserve unrelated source")
    before = hashes(directory)
    original_svg, original_pdf = author_export._svg, author_export._pdf

    def drift_svg(*args, **kwargs):
        original_svg(*args, **kwargs)
        path = args[4]
        tree = ET.parse(path)
        cut = tree.find(f".//{NS}g[@data-role='CUT']/{NS}path")
        cut.set("d", re.sub(r"(?<![\d.])10(?![\d.])", "10.0003", cut.attrib["d"]))
        tree.write(path, encoding="utf-8", xml_declaration=True)

    def drift_pdf(*args, **kwargs):
        result = original_pdf(*args, **kwargs)
        path = args[3]
        reader, writer = PdfReader(path), PdfWriter()
        for page in reader.pages:
            raw = page.get_contents().get_data()
            cut = b"30 10 l 20 10 l 0 10 l"
            assert raw.count(cut) == 1
            raw = raw.replace(cut, b"30 10.0006 l 20 10.0006 l 0 10.0006 l")
            stream = DecodedStreamObject()
            stream.set_data(raw)
            page[NameObject("/Contents")] = stream
            writer.add_page(page)
        with open(path, "wb") as output:
            writer.write(output)
        return result

    monkeypatch.setattr(author_export, "_svg", drift_svg)
    monkeypatch.setattr(author_export, "_pdf", drift_pdf)
    with pytest.raises(CurveOutputError, match="plocha zdroj") as caught:
        author_export.export_all(snapshot, directory)
    outputs = caught.value.report["lofts"][sid]["outputs"]
    assert float(
        Fraction(outputs["svg"]["source_to_actual_area_error_bound_exact"])
    ) == pytest.approx(0.009)
    assert float(
        Fraction(outputs["pdf"]["source_to_actual_area_error_bound_exact"])
    ) == pytest.approx(0.018)
    assert hashes(directory) == before
