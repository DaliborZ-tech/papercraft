def test_ld02_r20_h200_area_direct_to_both_actual_outputs_is_4000pi(
    tmp_path,
    record_property,
):
    started = time.perf_counter()
    p = AuthorProject.new(scale=1)
    a = p.add_profile(
        segments=[
            {
                "kind": "arc",
                "start": [20, 0],
                "end": [-20, 0],
                "data": {"center": [0, 0], "sweep_deg": 180},
            },
        ],
        closed=False,
    )
    b = p.copy_profile(a, plane={"origin": [0, 0, 200], "u": [1, 0, 0], "v": [0, 1, 0]})
    source = copy.deepcopy(p.profiles)
    sid, pid = finish(p, a, b)
    snapshot = p.snapshot()
    record_property(
        "commands", len(snapshot["pages"][0]["parts"][0]["paths"]["CUT"][0]["commands"])
    )
    record_property("core_seconds", time.perf_counter() - started)
    before = author_export.canonical_digest(snapshot)
    t = time.perf_counter()
    author_export.export_all(snapshot, tmp_path / "bundle")
    record_property("writer_seconds", time.perf_counter() - t)
    record = assert_actual_reports(tmp_path / "bundle", sid, pid)
    expected = 4000 * math.pi  # Independent intrinsic R*angle*height.
    budget = max(0.01, expected * 1e-6)
    for kind, output in record["outputs"].items():
        areas = [float(Fraction(v)) for v in output["area_exact"]]
        record_property(kind + "_area_bounds_mm2", json.dumps(areas))
        assert max(abs(v - expected) for v in areas) <= budget
    assert author_export.canonical_digest(snapshot) == before and p.profiles == source


